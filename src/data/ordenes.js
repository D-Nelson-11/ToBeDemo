//   estado      → 'abierta' | 'cerrada'   (lo cierra/abre el usuario)
//   activa      → true | false            (inactivar = sacarla de la operación)
//   pendiente   → 'pago' | 'fechas' | 'programar' | null
//   ultEmbarque → última vez que ese producto ingresó desde ese proveedor

const m = (codigo, nombre, categoria, cantidad, unidad, precio) => ({
  codigo,
  nombre,
  categoria,
  cantidad,
  unidad,
  precio,
})


// Las salidas van relativas a hoy: así el demo siempre tiene embarques en cada
// segmento de la torre, sin importar el día en que se abra.
const rel = (dias) => {
  const d = new Date()
  d.setHours(0, 0, 0, 0)
  d.setDate(d.getDate() + dias)
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(
    d.getDate(),
  ).padStart(2, '0')}`
}

